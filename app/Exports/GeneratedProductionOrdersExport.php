<?php

namespace App\Exports;

use Illuminate\Support\Facades\Session;
use Maatwebsite\Excel\Concerns\FromCollection;
use Maatwebsite\Excel\Concerns\WithHeadings;

class GeneratedProductionOrdersExport implements FromCollection, WithHeadings
{
    /**
     * @return \Illuminate\Support\Collection
     */
    public function collection()
    {
        $export = Session::get('session_export_data');
        return $export;
    }

    public function headings(): array
    {
        return
            [
                'Production Order No', 'Transaction Date', 'Line No', 'Line Type', 'Item No', 'Item Description', 'Quantity', 'UOM', 'Location', 'Bin', 'Routing', 'Process', 'Recipe', 'Step', 'Ext. Document No', 'Batch No', 'Weighed Item', 'Packed Item', 'Net Weight', 'IDT No', 'Published?', 'Generated By', 'Generated At'
            ];
    }
}
